"""check addon — the rules a shared Godot add-on keeps so a game can own its tree.

A game that installs an add-on owns its scene tree, its input actions, its
audio buses and its theme. An add-on that edits any of them at runtime moves
that ownership out of the game's files and into code nobody reads. Five rules,
opt-in (name `addon` in `[roster] checks`):

  root-add-child      `get_tree().root.add_child(...)`, `get_root().add_child`,
                      `root.add_child.call_deferred(...)` or
                      `root.call_deferred("add_child", ...)`: a node added to
                      the tree root outside any scene is a hidden autoload.
  tree-meta           `get_tree().set_meta(...)` or
                      `Engine.get_main_loop().set_meta(...)`: meta on the main
                      loop is a global variable.
  runtime-input-audio `InputMap.add_action(...)` or `AudioServer.add_bus(...)`:
                      actions belong in project.godot and buses in
                      default_bus_layout.tres, where the game can see them.
  theme-key-literal   a string literal assigned to `theme_type_variation` or
                      passed first to `get_theme_*(...)` or
                      `add_theme_*_override(...)`. Only when
                      `[addon] theme_keys_class` names the project's constants
                      class; off otherwise.
  uid-missing         a .gd with no .gd.uid sidecar, or a .tscn/.tres header
                      with no uid. An add-on that ships without them gets new
                      uids minted in every game that imports it, so no two
                      games agree. `check addon --fix` mints them: a fresh
                      random uid in the engine's text form, drawn again while
                      any file in the project already claims it — what
                      `scene new` does and what ResourceUID.create_id does.

A line opts out of a code rule with a comment that names the rule AND says
why: `# lint-allow: root-add-child -- the debug console outlives scenes`. An
opt-out with no reason is itself a finding. A file opts out of uid-missing in
config, also with a reason: `uid_exempt = { "addons/kit/gen.gd" = "why" }`.

Scope: the files under `[addon] paths` (globs, `**` crosses folders; stock
`addons/**`) minus `exclude`, tracked or new and not ignored — what the add-on
will ship. The code rules read `.gd`; uid-missing reads `.gd`, `.tscn` and
`.tres`. A scope holding no .gd FAILS (rule 4). Every rule prints its census.

`--fix` repairs uid-missing only. It writes each sidecar as `uid://…` plus a
newline and adds ` uid="uid://…"` at the end of a header line; no other byte
changes. A header it cannot prove (not a `[gd_scene`/`[gd_resource` line, a
format below 3, not closed by `]`) is REFUSED and written nowhere. The whole
repair is one plan: anything blocked, nothing is written.

HONEST SCOPE: matching is per line over the code before a `#` comment (string
literals are skipped when finding the comment). A call spread over lines, or
reached through a variable (`var r := get_tree().root; r.add_child(n)`), is
not seen.

godot-devkit.toml:
    [addon]
    paths = ["addons/kit/**"]
    exclude = ["addons/kit/demo/**"]
    theme_keys_class = "KitThemeKeys"
    uid_exempt = { "addons/kit/gen/tmp.gd" = "regenerated by the build" }
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from godot_devkit.core import apply
from godot_devkit.core.config import (ConfigError, config_section,
                                      repo_path_defect, str_tuple, table, text)
from godot_devkit.core.project import git_lines, repo_root
from godot_devkit.godot.checks.patterns import ALLOW_RE, glob_re
from godot_devkit.godot.index.uid_codec import mint, text_to_id
from godot_devkit.godot.index.uid_index import project_uids

SECTION = 'addon'
TAG = '[check:addon]'
DEFAULT_PATHS = ('addons/**',)
GD = '.gd'
RESOURCES = ('.tscn', '.tres')
UID_SUFFIX = '.uid'
HEADERS = ('[gd_scene', '[gd_resource')
HEADER_UID = re.compile(r'\buid="')
HEADER_FORMAT = re.compile(r'\bformat=(\d+)')
MIN_UID_FORMAT = 3
REASON_RE = re.compile(r'^\s*(?:--|—|:)?\s*(.*?)\s*$')
FIX_FLAG = '--fix'

_TREE = r'(?:get_tree\(\)|Engine\s*\.\s*get_main_loop\(\))\s*\.\s*'
_ROOT = _TREE + r'(?:root|get_root\(\))\s*\.\s*'
_LITERAL = r'&?["\']'


@dataclass(frozen=True)
class CodeRule:
    id: str
    regex: re.Pattern
    message: str


ROOT_ADD_CHILD = CodeRule(
    'root-add-child',
    re.compile(_ROOT + r'(?:add_child\b|call_deferred\s*\(\s*' + _LITERAL + r'add_child\b)'),
    'a node added to the tree root outside a scene is a hidden autoload; '
    'let a scene the game owns hold it')
TREE_META = CodeRule(
    'tree-meta',
    re.compile(_TREE + r'set_meta\s*\('),
    'meta on the SceneTree is global state; pass the object, or hold it in a '
    'Resource or a scene node')
RUNTIME_INPUT_AUDIO = CodeRule(
    'runtime-input-audio',
    re.compile(r'\b(?:InputMap\s*\.\s*add_action|AudioServer\s*\.\s*add_bus)\s*\('),
    'declare input actions in project.godot and audio buses in '
    'default_bus_layout.tres, not at runtime')
THEME_KEY_ID = 'theme-key-literal'
THEME_KEY_RE = re.compile(
    r'\btheme_type_variation\s*=\s*' + _LITERAL
    + r'|\b(?:get_theme_\w+|add_theme_\w+_override)\s*\(\s*' + _LITERAL)
UID_RULE = 'uid-missing'


@dataclass(frozen=True)
class Scope:
    paths: tuple[re.Pattern, ...]
    exclude: tuple[re.Pattern, ...]
    theme_keys_class: str
    uid_exempt: dict[str, str]


def _scope(sect: dict) -> Scope:
    paths = str_tuple(sect, SECTION, 'paths', DEFAULT_PATHS)
    exclude = str_tuple(sect, SECTION, 'exclude', ())
    theme_class = text(sect, SECTION, 'theme_keys_class', '')
    if theme_class and not re.fullmatch(r'[A-Za-z_]\w*', theme_class):
        raise ConfigError(f'[{SECTION}] theme_keys_class {theme_class!r} is not a class name')
    exempt = table(sect, SECTION, 'uid_exempt', {})
    for rel, why in exempt.items():
        defect = repo_path_defect(rel)
        if defect:
            raise ConfigError(f'[{SECTION}] uid_exempt entry {rel!r} {defect}')
        if not isinstance(why, str) or not why.strip():
            raise ConfigError(f'[{SECTION}] uid_exempt.{rel!r} needs a reason, got {why!r}')
    return Scope(tuple(glob_re(g) for g in paths), tuple(glob_re(g) for g in exclude),
                 theme_class, dict(exempt))


def code_part(line: str) -> tuple[str, str]:
    """(code, comment): the line split at the first `#` outside a string."""
    quote = ''
    i = 0
    while i < len(line):
        char = line[i]
        if quote:
            if char == '\\':
                i += 1
            elif char == quote:
                quote = ''
        elif char in '"\'':
            quote = char
        elif char == '#':
            return line[:i], line[i:]
        i += 1
    return line, ''


def scan_code(content: str, rel: str, rules: list[CodeRule],
              ) -> tuple[list[str], int]:
    """(findings, opt-outs honoured) for the code rules over one .gd file."""
    findings: list[str] = []
    allowed = 0
    for lineno, line in enumerate(content.split('\n'), start=1):
        code, comment = code_part(line)
        for rule in rules:
            if not rule.regex.search(code):
                continue
            optout = ALLOW_RE.search(comment)
            if optout and rule.id in re.split(r'\s*,\s*', optout.group(1)):
                reason = REASON_RE.match(comment[optout.end():]).group(1)
                if reason:
                    allowed += 1
                    continue
                findings.append(f'{rel}:{lineno}: {rule.id}: the opt-out needs a '
                                f'reason — `# lint-allow: {rule.id} -- <why>`')
                continue
            findings.append(f'{rel}:{lineno}: {rule.id}: {rule.message}')
    return findings, allowed


@dataclass
class Mint:
    """One uid-missing finding: a sidecar to write or a header to extend."""
    rel: str
    sidecar: bool
    body: str | None = None      # the header file's text; None for a sidecar
    refusal: str = ''

    def header_with(self, uid: str) -> str:
        first, sep, rest = self.body.partition('\n')
        return first[:-1] + f' uid="{uid}"]' + sep + rest


def _header_need(rel: str, body: str) -> Mint | None:
    """The Mint a resource needs, or None when its header holds a uid."""
    first = body.partition('\n')[0].rstrip('\r')
    if not first.startswith(HEADERS):
        return Mint(rel, False, body, 'its first line is not a [gd_scene/[gd_resource header')
    if HEADER_UID.search(first):
        return None
    if body.partition('\n')[0].endswith('\r') or not first.endswith(']'):
        return Mint(rel, False, body, 'its header line does not end in `]`')
    fmt = HEADER_FORMAT.search(first)
    if fmt is None or int(fmt.group(1)) < MIN_UID_FORMAT:
        return Mint(rel, False, body, f'its header has no format={MIN_UID_FORMAT} or '
                                      f'later; a uid needs Godot 4 text')
    return Mint(rel, False, body)


def _in_scope(rel: str, scope: Scope) -> bool:
    return (any(g.match(rel) for g in scope.paths)
            and not any(g.match(rel) for g in scope.exclude))


def _declares_class(root: Path, tracked: list[str], name: str) -> bool:
    decl = re.compile(rf'^\s*class_name\s+{re.escape(name)}\b', re.M)
    for rel in tracked:
        if rel.endswith(GD):
            try:
                if decl.search((root / rel).read_text(encoding='utf-8', errors='replace')):
                    return True
            except OSError:
                continue
    return False


def _repair(root: Path, needs: list[Mint]) -> tuple[list[str], int]:
    """Mint every repairable need as ONE plan. (report lines, minted count)."""
    taken = project_uids(root)
    plan = apply.Plan()
    lines: list[str] = []
    for need in needs:
        uid = mint(taken)
        taken.add(text_to_id(uid))
        if need.sidecar:
            plan.overwrite(root / (need.rel + UID_SUFFIX), uid + '\n')
            lines.append(f'  MINTED  {need.rel}{UID_SUFFIX} : {uid}')
        else:
            plan.overwrite(root / need.rel, need.header_with(uid))
            lines.append(f'  MINTED  {need.rel} header : {uid}')
    if not plan.steps:
        return lines, 0
    applied = plan.apply()
    if applied.blocked or applied.failed is not None:
        landed = {step.dest for step in applied.landed}
        out = [f'  BLOCKED  {b.describe()}' for b in applied.blocked]
        if applied.failed is not None:
            out.append(f'  FAILED  {applied.error}')
        return out + [f'  MINTED  {s.dest.relative_to(root).as_posix()}'
                      for s in plan.steps if s.dest in landed], len(landed)
    return lines, len(plan.steps)


def run(fix: bool = False) -> int:
    scope = _scope(config_section(SECTION))
    root = repo_root()
    tracked = git_lines('ls-files')
    shipped = sorted(set(tracked) | set(git_lines('ls-files', '--others',
                                                  '--exclude-standard')))
    files = [rel for rel in shipped if _in_scope(rel, scope)]
    gd = [rel for rel in files if rel.endswith(GD)]
    resources = [rel for rel in files if rel.endswith(RESOURCES)]

    rules = [ROOT_ADD_CHILD, TREE_META, RUNTIME_INPUT_AUDIO]
    if scope.theme_keys_class:
        if not _declares_class(root, tracked, scope.theme_keys_class):
            raise ConfigError(f'[{SECTION}] theme_keys_class {scope.theme_keys_class!r}: '
                              f'no tracked .gd declares `class_name '
                              f'{scope.theme_keys_class}`')
        rules.append(CodeRule(THEME_KEY_ID, THEME_KEY_RE,
                              f'use a {scope.theme_keys_class} constant, not a string '
                              f'literal theme key'))

    by_rule: dict[str, list[str]] = {rule.id: [] for rule in rules}
    allowed: dict[str, int] = dict.fromkeys(by_rule, 0)
    unreadable: list[str] = []
    for rel in gd:
        try:
            content = (root / rel).read_text(encoding='utf-8', errors='replace')
        except OSError:
            unreadable.append(rel)
            continue
        for rule in rules:
            hits, ok = scan_code(content, rel, [rule])
            by_rule[rule.id].extend(hits)
            allowed[rule.id] += ok

    needs: list[Mint] = []
    exempted = 0
    for rel in gd:
        if (root / rel).is_file() and not (root / (rel + UID_SUFFIX)).exists():
            if rel in scope.uid_exempt:
                exempted += 1
            else:
                needs.append(Mint(rel, True))
    for rel in resources:
        try:
            body = (root / rel).read_bytes().decode('utf-8')
        except (OSError, UnicodeDecodeError):
            unreadable.append(rel)
            continue
        need = _header_need(rel, body)
        if need is None:
            continue
        if rel in scope.uid_exempt:
            exempted += 1
        else:
            needs.append(need)
    in_scope = set(gd) | set(resources)
    stale = [rel for rel in sorted(scope.uid_exempt) if rel not in in_scope]

    minted_lines: list[str] = []
    minted = 0
    refused = [n for n in needs if n.refusal]
    if fix:
        minted_lines, minted = _repair(root, [n for n in needs if not n.refusal])
    open_needs = refused if fix else needs

    findings = 0
    for rule in rules:
        hits = by_rule[rule.id]
        findings += len(hits)
        print(f'{TAG} {rule.id} — {len(gd)} .gd scanned, {len(hits)} hit(s), '
              f'{allowed[rule.id]} opt-out(s) with a reason')
        for hit in hits:
            print(hit)
    if not scope.theme_keys_class:
        print(f'{TAG} {THEME_KEY_ID} — off: [{SECTION}] theme_keys_class is not set')
    print(f'{TAG} {UID_RULE} — {len(gd)} .gd and {len(resources)} .tscn/.tres '
          f'scanned, {len(needs)} missing, {exempted} exempt with a reason')
    for line in minted_lines:
        print(line)
    for need in open_needs:
        if need.refusal:
            print(f'{need.rel}: {UID_RULE}: REFUSED — {need.refusal}; mint it in the '
                  f'editor')
        elif need.sidecar:
            print(f'{need.rel}: {UID_RULE}: no {need.rel}{UID_SUFFIX} sidecar; '
                  f'{FIX_FLAG} mints it')
        else:
            print(f'{need.rel}: {UID_RULE}: its header has no uid; {FIX_FLAG} mints it')
    for rel in stale:
        print(f'{rel}: {UID_RULE}: STALE — [{SECTION}] uid_exempt names a file '
              f'not in scope')
    for rel in unreadable:
        print(f'  UNVERIFIED  {rel} — listed by git but not readable; not scanned')
    findings += len(open_needs) + len(stale) + (len(needs) - len(refused) - minted
                                                if fix else 0)
    if fix:
        print(f'{TAG} FIX — minted {minted} uid(s)' if minted
              else f'{TAG} FIX — nothing to mint')

    census = f'{len(gd)} .gd and {len(resources)} .tscn/.tres'
    if not gd:
        print(f'{TAG} FAIL — scanned 0 .gd of {len(files)} file(s) in scope '
              f'({len(shipped)} listed by git); check [{SECTION}] paths')
        return 1
    if findings:
        print(f'{TAG} FAIL — {findings} finding(s) across {census}')
        return 1
    print(f'{TAG} PASS — {len(rules) + 1} rule(s) across {census}, no findings')
    return 0
